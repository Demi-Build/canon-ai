# Minimal valid 1×1 transparent PNG (70 bytes), generated by PIL itself.
# The previous hand-rolled bytes had a truncated IDAT stream: PIL's lazy
# Image.open() accepted the header, but any full decode (convert, load)
# raised "broken data stream" — verified now by a round-trip DECODE, not
# just open (tests/test_backends_fake.py guards it).
_MIN_PNG_BYTES = bytes.fromhex(
    "89504e470d0a1a0a"              # PNG signature
    "0000000d49484452"              # IHDR chunk length + type
    "00000001"                      # width: 1
    "00000001"                      # height: 1
    "08060000001f15c489"            # bit depth 8, RGBA, CRC
    "0000000d49444154"              # IDAT chunk length + type
    "789c6360606060000000050001"    # zlib-compressed 1×1 transparent pixel
    "a5f64540"                      # CRC
    "0000000049454e44ae426082"      # IEND
)

# Minimal *valid silent* MP3 — a run of MPEG-1 Layer III frames (128kbps,
# 44.1kHz, ~0.42s total) carrying zeroed audio data, capped with an ID3v1
# trailer so decoders stop cleanly at end-of-stream instead of resyncing into
# zeros.  Loads WITHOUT warnings through both pygame.mixer.Sound and
# pygame.mixer.music.load (verified against pygame 2.6 / SDL_mixer 2.28).
#
# This is a *placeholder*: fake-asset runs write silent audio so the data tree
# is complete and loads cleanly, but no real audio is generated.  Consumers
# detect placeholder assets via the "fake" backend names recorded in
# generation_stats.json / manifest.json — see GenerationStats.
_SILENT_MP3_FRAME = b"\xff\xfb\x90\x00" + b"\x00" * 413  # one 417-byte L3 frame
_MIN_MP3_BYTES = _SILENT_MP3_FRAME * 16 + b"TAG" + b"\x00" * 125



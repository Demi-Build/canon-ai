class FakeImageBackend:
    """Deterministic image backend for tests.

    Copies a placeholder PNG from ``asset_dir`` to the requested save path.
    Records every call to ``.calls`` for assertion.

    Public utility — downstream users testing canon pipelines without
    paying for fal.ai calls.

    Args:
        asset_dir: Directory containing one or more PNG files.
        placeholder: Specific PNG path; takes precedence over ``asset_dir``.

    If neither is provided, a minimal 1×1 transparent PNG is generated inline.
    """

    #: The fake-transparency gate (platformer pack ``tileset_art``)
    #: passes trusted-alpha backends through untouched: placeholder
    #: bytes are not generated art, and the fake twins' $0 runs must
    #: stay byte-identical with identical call counts.
    trusted_alpha = True

    def __init__(
        self,
        asset_dir: str | Path | None = None,
        placeholder: str | Path | None = None,
        capabilities: frozenset[str] | set[str] | None = None,
    ) -> None:
        self.asset_dir = Path(asset_dir) if asset_dir else None
        self.placeholder = Path(placeholder) if placeholder else None
        self.calls: list[dict] = []
        # Declarable per test (graphics arc): lets $0 tests exercise
        # capability degradation (a fake claiming native_pixels skips
        # grid-snap; one without animation_sheets forces the static
        # fallback). None = the derived default set.
        if capabilities is not None:
            self.capabilities = frozenset(capabilities)

    def generate(self, prompt: str, width: int, height: int) -> bytes:
        """Return placeholder PNG bytes and record the call."""
        self.calls.append({"prompt": prompt, "width": width, "height": height})
        return self._placeholder_bytes()

    async def generate_async(self, prompt: str, width: int, height: int) -> bytes:
        """Async variant of ``generate``."""
        return self.generate(prompt, width, height)

    def generate_and_save(
        self, prompt: str, filepath: str, width: int, height: int
    ) -> bool:
        """Write placeholder PNG to ``filepath`` and record the call."""
        self.calls.append(
            {"prompt": prompt, "filepath": filepath, "width": width, "height": height}
        )
        dest = Path(filepath)
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_bytes(self._placeholder_bytes())
        return True

    async def generate_and_save_async(
        self, prompt: str, filepath: str, width: int, height: int
    ) -> bool:
        """Async variant of ``generate_and_save``."""
        return self.generate_and_save(prompt, filepath, width, height)

    # -- img2img (implements ``ImageEditBackend``) --------------------------

    def edit(
        self,
        image_bytes: bytes,
        prompt: str,
        width: int,
        height: int,
        references: list[bytes] | None = None,
    ) -> bytes:
        """Return a deterministic canned multi-frame sprite SHEET and record
        the call. The sheet holds ``_EDIT_SHEET_FRAMES`` opaque blobs on a
        white field, evenly spaced with clear gaps, so content-aware frame
        segmentation recovers exactly that many frames — the animation slicing
        path runs at $0. ``references`` are RECORDED (count) but do not change
        the output, so fake runs stay byte-identical. Byte-identical for
        identical ``(width, height)``."""
        self.calls.append(
            {
                "op": "edit",
                "prompt": prompt,
                "width": width,
                "height": height,
                "image_bytes": len(image_bytes),
                "references": len(references or []),
            }
        )
        return self._edit_sheet_bytes(width, height)

    async def edit_async(
        self,
        image_bytes: bytes,
        prompt: str,
        width: int,
        height: int,
        references: list[bytes] | None = None,
    ) -> bytes:
        """Async variant of ``edit``."""
        return self.edit(image_bytes, prompt, width, height, references)

    #: Frame count the canned edit sheet draws — a fixed, evenly-spaced count
    #: so segmentation is deterministic. Real img2img ignores exact counts;
    #: the animation phase records whatever it segments, not this number.
    _EDIT_SHEET_FRAMES = 4

    @classmethod
    def _edit_sheet_bytes(cls, width: int, height: int) -> bytes:
        """Deterministic white-background sheet of evenly-spaced opaque blobs.
        Falls back to the 1×1 stub only if Pillow is somehow absent (the pack
        always installs it; the animation path needs it regardless)."""
        try:
            from PIL import Image, ImageDraw
        except ImportError:  # pragma: no cover — pack installs Pillow
            return _MIN_PNG_BYTES
        w, h = max(cls._EDIT_SHEET_FRAMES, width), max(4, height)
        img = Image.new("RGBA", (w, h), (255, 255, 255, 255))
        draw = ImageDraw.Draw(img)
        cell = w // cls._EDIT_SHEET_FRAMES
        radius = max(2, min(cell, h) // 3)
        cy = h // 2
        for i in range(cls._EDIT_SHEET_FRAMES):
            cx = i * cell + cell // 2
            draw.ellipse(
                [cx - radius, cy - radius, cx + radius, cy + radius],
                fill=(60, 90, 200, 255),
            )
            # a per-frame "leg" nub so slices differ yet stay deterministic
            leg = radius + (i % 3)
            draw.rectangle([cx - 2, cy, cx + 2, cy + leg], fill=(60, 90, 200, 255))
        buf = io.BytesIO()
        img.save(buf, format="PNG")
        return buf.getvalue()

    def _placeholder_bytes(self) -> bytes:
        if self.placeholder and self.placeholder.exists():
            return self.placeholder.read_bytes()
        if self.asset_dir and self.asset_dir.exists():
            pngs = list(self.asset_dir.glob("*.png"))
            if pngs:
                return pngs[0].read_bytes()
        return _MIN_PNG_BYTES


